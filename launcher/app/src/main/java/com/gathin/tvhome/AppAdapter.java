    private void sizeForMosaic(Holder h, int position) {
        View item = h.itemView;
        float density = item.getResources().getDisplayMetrics().density;
        RecyclerView rv = mosaicGrid;
        int inner = rv != null && rv.getWidth() > 0 ? rv.getWidth() - rv.getPaddingLeft() - rv.getPaddingRight()
                : item.getResources().getDisplayMetrics().widthPixels - Math.round(96 * density);
        int innerH = rv != null && rv.getHeight() > 0 ? rv.getHeight() - rv.getPaddingTop() - rv.getPaddingBottom() : 0;
        android.graphics.Rect r = MosaicLayoutManager.rect(position, inner, innerH, density);
        // The card fills the cell; the name moves inside it, bottom-left, as on a poster.
        item.setPadding(0, 0, 0, 0);
        int w = r.width(), hgt = r.height();
        ViewGroup.MarginLayoutParams cardLp = (ViewGroup.MarginLayoutParams) h.card.getLayoutParams();
        // The card fills the cell the layout manager measured: gaps stay exact whatever the sizes
        cardLp.width = ViewGroup.LayoutParams.MATCH_PARENT;
        cardLp.height = ViewGroup.LayoutParams.MATCH_PARENT;
        cardLp.setMargins(0, 0, 0, 0);
        h.card.setLayoutParams(cardLp);
        h.name.setVisibility(View.GONE);
        boolean hero = MosaicLayoutManager.isBig(position);
        // Title: bottom-left inside the card, on a soft fade (white text stays >= 4.5:1 on any card colour)
        h.label.setText(labelAt(position));
        h.label.setVisibility(View.VISIBLE);
        h.label.setGravity(android.view.Gravity.START | android.view.Gravity.BOTTOM);
        h.label.setTextSize(android.util.TypedValue.COMPLEX_UNIT_SP, hero ? 18 : 14);
        h.label.setTypeface(android.graphics.Typeface.create("sans-serif-medium", android.graphics.Typeface.NORMAL));
        Entry entry = position < items.size() ? items.get(position) : null;
        int bottomColor = entry != null && entry.backdrop != null && entry.backdrop.length > 0
                ? entry.backdrop[entry.backdrop.length - 1] : 0xFF1E1E1E;
        double lum = (0.299 * ((bottomColor >> 16) & 255) + 0.587 * ((bottomColor >> 8) & 255)
                + 0.114 * (bottomColor & 255)) / 255.0;
        boolean lightCard = lum > 0.6;
        h.label.setTextColor(lightCard ? 0xFF111418 : 0xFFFFFFFF);
        if (lightCard) h.label.setShadowLayer(0, 0, 0, 0);
        else h.label.setShadowLayer(4 * density, 0, density, 0x80000000);
        int pad = Math.round((hero ? 20 : 12) * density);              // card padding on the 8-pt grid
        h.label.setPadding(pad, Math.round(24 * density), pad, Math.round((hero ? 16 : 10) * density));
        h.label.setSingleLine(true);
        android.graphics.drawable.GradientDrawable scrim = new android.graphics.drawable.GradientDrawable(
                android.graphics.drawable.GradientDrawable.Orientation.TOP_BOTTOM, new int[]{0x00000000, 0x99000000});
        float rad = 6 * density;
        scrim.setCornerRadii(new float[]{0, 0, 0, 0, rad, rad, rad, rad});
        h.label.setBackground(lightCard ? null : scrim);   // light cards need no fade for dark text
        // Logo: one fixed size for every card (hero larger), centred and nudged up clear of the title
        int logo = Math.round((hero ? 88 : 48) * density);
        android.widget.FrameLayout.LayoutParams iconLp = (android.widget.FrameLayout.LayoutParams) h.icon.getLayoutParams();
        iconLp.width = iconLp.height = logo;
        iconLp.gravity = android.view.Gravity.CENTER;
        iconLp.setMargins(0, 0, 0, 0);   // exact centre, left/right and top/bottom
        h.icon.setLayoutParams(iconLp);
        h.banner.setScaleType(android.widget.ImageView.ScaleType.FIT_CENTER);
        // Focus ring drawn on the card's own edge: same size, same 16dp corners, can never drift off the card
        applyRing(h, entry, 6 * density, density);
    }

    /** The focus ring on the card's own edge: a white (or app-coloured) line with a dark one just inside it. */
    private void applyRing(Holder h, Entry entry, float radius, float density) {
        if (android.os.Build.VERSION.SDK_INT >= 23) {
            android.graphics.drawable.GradientDrawable outer = new android.graphics.drawable.GradientDrawable();
            outer.setCornerRadius(radius);
            outer.setColor(0x00000000);
            int ringColor = BRAND_RING && entry != null && entry.ambient != 0 ? vivid(entry.ambient) : 0xFFFFFFFF;
            outer.setStroke(Math.round(3 * density), ringColor);
            android.graphics.drawable.GradientDrawable innerLine = new android.graphics.drawable.GradientDrawable();
            innerLine.setCornerRadius(Math.max(0f, radius - 2 * density));
            innerLine.setColor(0x00000000);
            innerLine.setStroke(Math.max(1, Math.round(1.5f * density)), 0xCC0E1320);
            android.graphics.drawable.LayerDrawable ring = new android.graphics.drawable.LayerDrawable(
                    new android.graphics.drawable.Drawable[]{outer, innerLine});
            int in3 = Math.round(3 * density);
            ring.setLayerInset(1, in3, in3, in3, in3);   // dark line just inside the white one
            android.graphics.drawable.StateListDrawable fg = new android.graphics.drawable.StateListDrawable();
            fg.addState(new int[]{android.R.attr.state_focused}, ring);
            fg.addState(new int[]{}, new android.graphics.drawable.ColorDrawable(0));
            h.card.setForeground(fg);
            h.ring = ring;
        }
    }

    /** Side list: a wide row, logo at the start and the name beside it, readable on light and dark cards. */
    private void sizeForSideList(Holder h, int position) {
        View item = h.itemView;
        float density = item.getResources().getDisplayMetrics().density;
        item.setPadding(0, Math.round(5 * density), 0, Math.round(5 * density));
        ViewGroup.MarginLayoutParams cardLp = (ViewGroup.MarginLayoutParams) h.card.getLayoutParams();
        cardLp.width = ViewGroup.LayoutParams.MATCH_PARENT;
        cardLp.height = Math.round(62 * density);
        cardLp.setMargins(0, 0, 0, 0);
        h.card.setLayoutParams(cardLp);
        h.name.setVisibility(View.GONE);
        Entry entry = position < items.size() ? items.get(position) : null;
        int bottom = entry != null && entry.backdrop != null && entry.backdrop.length > 0
                ? entry.backdrop[entry.backdrop.length - 1] : 0xFF1E1E1E;
        double lum = (0.299 * ((bottom >> 16) & 255) + 0.587 * ((bottom >> 8) & 255) + 0.114 * (bottom & 255)) / 255.0;
        h.label.setText(labelAt(position));
        h.label.setVisibility(View.VISIBLE);
        h.label.setBackground(null);
        h.label.setSingleLine(true);
        h.label.setGravity(android.view.Gravity.START | android.view.Gravity.CENTER_VERTICAL);
        h.label.setTextSize(android.util.TypedValue.COMPLEX_UNIT_SP, 17);
        h.label.setTypeface(android.graphics.Typeface.create("sans-serif-medium", android.graphics.Typeface.NORMAL));
        h.label.setTextColor(lum > 0.6 ? 0xFF111418 : 0xFFFFFFFF);
        h.label.setShadowLayer(0, 0, 0, 0);
        h.label.setPadding(Math.round(74 * density), 0, Math.round(16 * density), 0);
        android.widget.FrameLayout.LayoutParams labelLp = (android.widget.FrameLayout.LayoutParams) h.label.getLayoutParams();
        labelLp.height = ViewGroup.LayoutParams.MATCH_PARENT;
        labelLp.gravity = android.view.Gravity.CENTER_VERTICAL;
        h.label.setLayoutParams(labelLp);
        android.widget.FrameLayout.LayoutParams iconLp = (android.widget.FrameLayout.LayoutParams) h.icon.getLayoutParams();
        iconLp.width = iconLp.height = Math.round(40 * density);
        iconLp.gravity = android.view.Gravity.START | android.view.Gravity.CENTER_VERTICAL;
        iconLp.setMargins(Math.round(18 * density), 0, 0, 0);
        h.icon.setLayoutParams(iconLp);
        applyRing(h, entry, cornerRadius(Integer.MAX_VALUE, density), density);   // exactly on the row's edge
    }

    /** The focused app's logo, for the side list's preview. */
    Drawable previewAt(int position) {
        if (position < 0 || position >= items.size()) return null;
        Entry e = items.get(position);
        return e.icon != null ? e.icon : e.banner;
    }

    /** The focused app's card colours, top and bottom; null until sampled. */
    int[] backdropAt(int position) {
        return position < 0 || position >= items.size() ? null : items.get(position).backdrop;
    }

    static final class Holder extends RecyclerView.ViewHolder {
        final View card;
        /** item_app.xml's tile_bg: the dark card behind an icon tile, or behind a banner that has transparent parts. */
        final Drawable cardBackground;
        final ImageView banner;
        final ImageView icon;
        final TextView label;
        final TextView name;
        final boolean animations;
        final boolean advancedEffects;
        final boolean reducedMotion;
        /** Alpha of the name while the tile is not focused (always_show_names). */
        final float restNameAlpha;
        final boolean overshoot;
        /** A dock tile: it grows in place without advanced_effects' lift, which reads as off-centre in the band (#2135). */
        boolean inDock;
        /** The mosaic focus ring (pulse animates its alpha); null outside mosaic. */
        Drawable ring;
        private View shine;
        private android.animation.ValueAnimator pulse;

        Holder(View v, TileListener listener, boolean animations, boolean advancedEffects,
               boolean reducedMotion, float restNameAlpha, boolean overshoot) {
            super(v);
            card = v.findViewById(R.id.card);
            cardBackground = card.getBackground();
            banner = v.findViewById(R.id.banner);
            icon = v.findViewById(R.id.icon);
            label = v.findViewById(R.id.label);
            name = v.findViewById(R.id.name);
            this.animations = animations;
            this.advancedEffects = advancedEffects;
            this.reducedMotion = reducedMotion;
            this.restNameAlpha = restNameAlpha;
            this.overshoot = overshoot;

            final float density = v.getResources().getDisplayMetrics().density;
            card.setOutlineProvider(new ViewOutlineProvider() {
                @Override
                public void getOutline(View view, Outline outline) {
                    // 16dp at the design width, scaled down with the tile so small tiles keep the same shape.
                    outline.setRoundRect(0, 0, view.getWidth(), view.getHeight(), cornerRadius(view.getWidth(), density));
                }
            });
            card.setClipToOutline(true);
            if (card instanceof FrameLayout) {
                // focus_effect "shine": a soft band, made once here and only ever moved and faded, so focusing a
                // tile never adds a view (which would lay the whole mosaic out again and nudge it)
                shine = new View(card.getContext());
                shine.setBackground(new android.graphics.drawable.GradientDrawable(
                        android.graphics.drawable.GradientDrawable.Orientation.LEFT_RIGHT,
                        new int[]{0x00FFFFFF, 0x00FFFFFF, 0x66FFFFFF, 0x00FFFFFF, 0x00FFFFFF}));
                shine.setRotation(18f);
                shine.setScaleY(1.8f);
                shine.setAlpha(0f);
                shine.setImportantForAccessibility(View.IMPORTANT_FOR_ACCESSIBILITY_NO);
                ((FrameLayout) card).addView(shine, new FrameLayout.LayoutParams(
                        ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.MATCH_PARENT));
            }

            card.setOnKeyListener((view, keyCode, event) -> {
                if (event.getAction() != KeyEvent.ACTION_DOWN) return false;
                if (keyCode != KeyEvent.KEYCODE_DPAD_UP && keyCode != KeyEvent.KEYCODE_DPAD_DOWN
                        && keyCode != KeyEvent.KEYCODE_DPAD_LEFT && keyCode != KeyEvent.KEYCODE_DPAD_RIGHT) return false;
                int pos = getBindingAdapterPosition();
                return listener != null && pos != RecyclerView.NO_POSITION && listener.onTileVerticalKey(pos, keyCode);
            });

            card.setOnFocusChangeListener((view, focused) -> {
                view.animate().cancel();
                banner.animate().cancel();
                name.animate().cancel();
                float scale = !animations || (MOSAIC && "border".equals(FOCUS_FX)) ? 1f : MOSAIC
                        // grow by 70% of one gutter in total: each side moves less than half a gap
                        ? 1f + MosaicLayoutManager.gap(density) * 0.7f / Math.max(1, Math.max(view.getWidth(), view.getHeight()))
                        : SIDE_LIST ? 1.03f : CAROUSEL ? 1f : advancedEffects ? 1.12f : 1.10f;
                float s = focused ? scale : 1f;
                if (!animations) {
                    view.setScaleX(1f);
                    view.setScaleY(1f);
                    view.setTranslationY(0f);
                    view.setTranslationZ(0f);
                    banner.setScaleX(1f);
                    banner.setScaleY(1f);
                    name.setAlpha(focused ? 1f : restNameAlpha);
                    name.setTranslationY(0f);
                } else if (reducedMotion) {
                    // A short zoom with no hardware layer: building a layer for so short an animation costs more
                    // frames than it saves. The name just appears instead of fading.
                    view.animate().scaleX(s).scaleY(s)
                            .translationY(focused && advancedEffects && !inDock && !MOSAIC ? -4f * density : 0f)
                            .translationZ(focused && advancedEffects && !MOSAIC ? 8f * density : 0f)
                            .setDuration(focused ? Motion.REDUCED_MS : 60)
                            .setInterpolator(new DecelerateInterpolator())
                            .start();
                    name.setAlpha(focused ? 1f : restNameAlpha);
                    // Same place as the full motion's slide ends: the layout's -6dp is only its starting point, and
                    // left there the name overlaps the zoomed tile.
                    // Only on focus: snapping it back to -6dp while it fades out would jump it up over the tile.
                    if (focused) name.setTranslationY(density * 4f);
                } else {
                    view.animate().scaleX(s).scaleY(s)
                            .translationY(focused && advancedEffects && !inDock && !MOSAIC ? -4f * density : 0f)
                            .translationZ(focused && advancedEffects && !MOSAIC ? 8f * density : 0f)
                            .setDuration(advancedEffects ? (focused ? 220 : 170) : (focused ? 260 : 180))
                            .setInterpolator(focused && (!overshoot || MOSAIC) ? new DecelerateInterpolator(1.5f)
                                    : new OvershootInterpolator(focused ? (advancedEffects ? 0.7f : 1.6f) : 0f))
                            .withLayer().start();
                    if (advancedEffects) {
                        banner.animate().scaleX(focused ? 1.035f : 1f).scaleY(focused ? 1.035f : 1f)
                                .setDuration(280).start();
                    }
                    name.animate().alpha(focused ? 1f : restNameAlpha)
                            .translationY(focused ? density * 4f : -density * 6f)
                            .setDuration(220).start();
                }
                int pos = getBindingAdapterPosition();
                focusEffect(focused, density);
                if (focused && listener != null && pos != RecyclerView.NO_POSITION) {
                    listener.onTileFocused(pos, view);
                }
            });
        }

        /** focus_effect extras on top of the zoom: a light sweep across the card, or a breathing ring. */
        private void focusEffect(boolean focused, float density) {
            if (pulse != null) {
                pulse.cancel();
                pulse = null;
            }
            if (ring != null) ring.setAlpha(255);
            if (shine != null && !focused) {
                shine.animate().cancel();
                shine.setAlpha(0f);
            }
            if (!focused || !animations || reducedMotion) return;
            if ("pulse".equals(FOCUS_FX) && ring != null) {
                pulse = android.animation.ValueAnimator.ofInt(255, 110);
                pulse.setDuration(950);
                pulse.setRepeatMode(android.animation.ValueAnimator.REVERSE);
                pulse.setRepeatCount(android.animation.ValueAnimator.INFINITE);
                pulse.setInterpolator(new android.view.animation.AccelerateDecelerateInterpolator());
                pulse.addUpdateListener(a -> {
                    ring.setAlpha((int) a.getAnimatedValue());
                    card.invalidate();
                });
                pulse.start();
            } else if ("shine".equals(FOCUS_FX) && shine != null && card.getWidth() > 0) {
                int w = card.getWidth();
                shine.animate().cancel();
                shine.setTranslationX(-w * 0.8f);
                shine.setAlpha(1f);
                shine.animate().translationX(w * 0.8f).setStartDelay(120).setDuration(1100)
                        .setInterpolator(new DecelerateInterpolator(1.4f))
                        .withEndAction(() -> shine.setAlpha(0f)).start();
            }
        }
    }
