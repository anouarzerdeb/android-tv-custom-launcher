    /** Staggered arrival of each tile, once per Home build and only right after it is built (not on scroll). */
    private void playEntrance(View v, int position) {
        if ("off".equals(ENTRANCE) || !animations || reducedMotion) return;
        if (android.os.SystemClock.uptimeMillis() - bornAt > 4000 || !entered.add(position)) return;
        float d = v.getResources().getDisplayMetrics().density;
        boolean pop = "pop".equals(ENTRANCE);
        v.setAlpha(0f);
        if (pop) {
            v.setScaleX(0.86f);
            v.setScaleY(0.86f);
        } else {
            v.setTranslationY(28 * d);
        }
        v.animate().alpha(1f).scaleX(1f).scaleY(1f).translationY(0f)
                .setStartDelay(Math.min(position, 14) * 80L)
                .setDuration(pop ? 700 : 900)
                .setInterpolator(pop ? new OvershootInterpolator(1.2f) : new DecelerateInterpolator(2f))
                .start();
    }

    /** A ring colour that stays visible: the app's hue, saturated and bright. */
    private static int vivid(int color) {
        float[] hsv = new float[3];
        android.graphics.Color.colorToHSV(color, hsv);
        if (hsv[1] < 0.15f) return 0xFFFFFFFF;   // greys and blacks: white reads better
        hsv[1] = Math.max(hsv[1], 0.6f);
        hsv[2] = Math.max(hsv[2], 0.95f);
        return android.graphics.Color.HSVToColor(hsv);
    }

    /** Span of a tile: first row 6/3/3 (tall), second 4/4/4, then 3/3/3/3. */
    static int mosaicSpan(int position) {
        if (position < 3) return position == 0 ? 6 : 3;
        if (position < 6) return 4;
        return 3;
    }

    /** Height factor of a tile's row, relative to a 3-span tile's usual 16:9-ish height. */
    private static float mosaicHeight(int position) {
        return position < 3 ? 1.75f : position < 6 ? 1.2f : 1f;
    }

